    /** Zwraca tablicę imion na podany dzień (domyślnie dzisiaj). */
    public static function get(?Carbon $date = null): array
    {
        $date ??= now();
        $key = $date->month . '-' . $date->day;

        return self::$calendar[$key] ?? [];
    }

    /** Zwraca imieniny jako string, np. "Helena, Ilona, Bogusław". */
    public static function format(?Carbon $date = null): string
    {
        $names = self::get($date);

        return implode(', ', $names);
    }
